/**
 * Gift category directory — parent sections + subcategory cards.
 * Cards link into the product listing with a category filter.
 */

function slugify(value) {
  return String(value || '')
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
}

function card(name, image) {
  return {
    name,
    slug: slugify(name),
    path: `/products?category=${encodeURIComponent(name)}`,
    image,
  }
}

